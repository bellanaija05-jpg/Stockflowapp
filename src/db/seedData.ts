/**
 * Generate initial per-store inventory.
 * We vary stock realistically: some products have healthy stock (15-30),
 * some have low stock (1-3) below reorder level, and a few have 0 to test out-of-stock.
 */
export function generateInitialInventory(): StoreInventory[] {
  const inventory: StoreInventory[] = [];
  let idCounter = 1;

  for (const store of SEED_STORES) {
    for (const prod of SEED_PRODUCTS) {
      let qty = 0;
      // Deterministic pseudo-random variation based on ids
      const hash = (store.id.charCodeAt(store.id.length - 1) * 7 + prod.id.charCodeAt(prod.id.length - 1) * 13) % 100;
      
      if (prod.sku === 'AIRPODS-PRO2-WHT') {
        // Specifically fulfill the user prompt's AirPods example:
        // Store 1: 15, Store 2: 8, Store 3: 0, Store 4: 23
        if (store.id === 'store-1') qty = 15;
        else if (store.id === 'store-2') qty = 8;
        else if (store.id === 'store-3') qty = 0;
        else if (store.id === 'store-4') qty = 23;
        else qty = (hash % 15) + 3;
      } else if (hash < 10) {
        // Out of stock
        qty = 0;
      } else if (hash < 25) {
        // Low stock (below reorderLevel)
        qty = Math.max(1, Math.floor(prod.reorderLevel / 2));
      } else if (hash < 60) {
        // Moderate stock
        qty = prod.reorderLevel + (hash % 8) + 2;
      } else {
        // High stock
        qty = prod.reorderLevel + 12 + (hash % 20);
      }

      inventory.push({
        id: `inv-${idCounter++}`,
        productId: prod.id,
        storeId: store.id,
        quantity: qty,
        updatedAt: '2026-03-01T08:00:00Z',
      });
    }
  }

  return inventory;
}

